// Bundles the drizzle migration SQL into src/migrations.generated.ts so the browser demo can apply
// the schema without a filesystem. Runs after `drizzle-kit generate` (see package.json "generate").
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const drizzleDir = resolve(here, "../drizzle");
const journal = JSON.parse(readFileSync(resolve(drizzleDir, "meta/_journal.json"), "utf8"));
const entries = journal.entries.map((entry) => ({ tag: entry.tag, sql: readFileSync(resolve(drizzleDir, `${entry.tag}.sql`), "utf8") }));

const out = `// Generated by scripts/bundle-migrations.mjs from drizzle/*.sql. Do not edit; run \`npm run generate -w packages/db\`.
export interface BundledMigration {
  tag: string;
  sql: string;
}

export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(resolve(here, "../src/migrations.generated.ts"), out);
console.log(`bundled ${entries.length} migration(s)`);
